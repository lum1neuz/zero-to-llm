from collections import namedtuple
from harness import test, fail, learner_fn, script_error, stdout

Row = namedtuple("Row", "model task item correct tokens")
# Model "a" writes long answers and is right half the time; "b" writes short ones and is right
# 3 times out of 4. Right and wrong answers have different lengths, so averaging over only the
# right ones gives a different number.
ROWS_T = [
    Row("a", "mn_qa", 1, 1, 60), Row("a", "mn_qa", 2, 0, 80), Row("a", "mn_qa", 3, 1, 50), Row("a", "mn_mc", 1, 0, 10),
    Row("b", "mn_qa", 1, 1, 30), Row("b", "mn_qa", 2, 1, 36), Row("b", "mn_qa", 3, 0, 44), Row("b", "mn_mc", 1, 1, 6),
]


def per_model(f):
    groups = {}
    for r in ROWS_T:
        groups.setdefault(r.model, []).append(r)
    return {m: f(g) for m, g in groups.items()}


TPA = per_model(lambda g: sum(r.tokens for r in g) / len(g))
TPR = per_model(lambda g: sum(r.tokens for r in g) / sum(r.correct for r in g))


def call(L, name):
    out = learner_fn(L, name)(list(ROWS_T))
    if out is None:
        fail(f"`{name}` returns nothing. It has to return a dict of model → tokens.")
    if out is Ellipsis or (isinstance(out, dict) and any(v is Ellipsis for v in out.values())):
        fail(f"`{name}` still returns `...` for every model, the placeholder.")
    if not isinstance(out, dict) or set(out) != set(TPA):
        fail(f"`{name}` should return one number per model, a dict with keys {sorted(TPA)}.")
    if any(isinstance(v, bool) or not isinstance(v, (int, float)) for v in out.values()):
        fail(f"`{name}` should give each model a number.")
    return {m: float(v) for m, v in out.items()}


def near(a, b):
    return all(abs(a[m] - b[m]) < 1e-6 for m in b)


def show(d):
    return ", ".join(f"{m}: {v:.1f}" for m, v in d.items())


@test("tokens_per_answer", "tokens_per_answer is each model's mean answer length")
def _(L):
    got = call(L, "tokens_per_answer")
    if near(got, TPA):
        return
    if near(got, per_model(lambda g: sum(r.tokens for r in g))):
        fail(f"You get {show(got)}: the total tokens of all a model's answers. Divide by how many answers it gave to get the mean length.")
    if near(got, per_model(lambda g: sum(r.tokens for r in g if r.correct) / sum(r.correct for r in g))):
        fail(f"You get {show(got)}: the mean over only the right answers. A model pays for every answer it generates, "
             "wrong ones included, so average over all of them.")
    fail(f"The mean answer lengths here are {show(TPA)}, but you get {show(got)}.")


@test("tokens_per_right_answer", "tokens_per_right_answer charges wrong answers too")
def _(L):
    got = call(L, "tokens_per_right_answer")
    if near(got, TPR):
        return
    if near(got, per_model(lambda g: sum(r.tokens for r in g if r.correct) / sum(r.correct for r in g))):
        fail(f"You get {show(got)}: the mean length of the right answers, as if wrong answers cost nothing. "
             "They cost the same tokens. Divide *every* token the model generated by the answers it got right.")
    if near(got, TPA):
        fail(f"You get {show(got)}, the same as tokens per answer: you divided by every answer. "
             "This one divides by the right answers only, so a model that's often wrong pays more per right answer.")
    if near(got, {m: 1 / v for m, v in TPR.items()}):
        fail(f"You get {', '.join(f'{m}: {v:.3f}' for m, v in got.items())}, right answers per token: upside down. Put the tokens on top.")
    fail(f"Tokens per right answer here should be {show(TPR)}, but you get {show(got)}.")


@test("script_runs", "The script runs and prints the table")
def _(L):
    err = script_error()
    if err:
        fail(f"Your script stopped at line {err['line']}: {err['diagnosis']}" if err.get("line") else f"Your script stopped: {err['diagnosis']}")
    if "tok/answer" not in stdout():
        fail("The table at the bottom of the script is missing. Put it back so you can compare the four models.")
